"""Turn Rev's RotatoCAM ANSI splash page (rotatocam.html, an 80x24 ANSI screen with animated parts)
into src/bbs/rotatocam_splash.h for the login flow.

usage: python tools/art/make_splash.py "C:/Users/rev/Downloads/rotatocam (1).html"
"""
import base64
import json
import re
import sys

src = open(sys.argv[1], encoding='utf-8').read()
D = json.loads(re.search(r'const D = (\{.*?\});\n', src, re.S).group(1))
grid = base64.b64decode(D['grid'])
w, h = D['w'], D['h']
assert len(grid) == w * h * 3, len(grid)

out = ['// SPDX-License-Identifier: GPL-3.0-or-later',
       '// Copyright (C) 2026 Rev. J. Money',
       '// Generated by tools/art/make_splash.py from Rev\'s RotatoCAM ANSI splash page. Do not edit.',
       '// Per cell: CP437 character, attribute (fg | bg << 4), animation tag (kSplashTags).',
       '#pragma once',
       '#include <stdint.h>',
       '',
       'static const int kSplashW = %d, kSplashH = %d;' % (w, h),
       'static const char* const kSplashTags[] = {%s};' % ', '.join('"%s"' % t for t in D['tags']),
       'static const uint8_t kSplashCycle[] = {%s};' % ', '.join(str(c) for c in D['cyc']),
       'static const char kSplashMarquee[] = "%s";' % D['msg'].replace('\\', '\\\\').replace('"', '\\"'),
       'static const uint8_t kSplashGrid[%d] = {' % len(grid)]
for i in range(0, len(grid), 24):
    out.append('    ' + ','.join(str(b) for b in grid[i:i + 24]) + ',')
out.append('};')
open('src/bbs/rotatocam_splash.h', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('wrote src/bbs/rotatocam_splash.h: %dx%d, %d tags' % (w, h, len(D['tags'])))
