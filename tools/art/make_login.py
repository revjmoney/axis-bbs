"""Draw the AXIS login (caller welcome) logo as an 80x12 CP437 ANSI file and a firmware header.

Original art: the WFC's block letters with a yellow-to-red paint gradient, a glossy highlight,
a dark drop shadow, multi-colour drips and spray-paint specks. The live board info is drawn
under it by the BBS (src/bbs/node.cpp). Edit art/login.ans in PabloDraw or Moebius if you like,
then run with --header-only to rebuild the header from the edited file.

usage: python -I tools/art/make_login.py art/login.ans src/bbs/login_art.h
       python -I tools/art/make_login.py --header-only art/login.ans src/bbs/login_art.h
"""
import random
import sys

W, H = 80, 12
FULL, DARK, MED, LIGHT, TOP, BOT, DOT = 0xDB, 0xB2, 0xB1, 0xB0, 0xDF, 0xDC, 0xFA

LETTERS = {
    'A': ["  █████  ", " ███ ███ ", "███   ███", "█████████", "███   ███", "███   ███", "███   ███"],
    'X': ["███   ███", " ███ ███ ", "  █████  ", "   ███   ", "  █████  ", " ███ ███ ", "███   ███"],
    'I': ["█████", " ███ ", " ███ ", " ███ ", " ███ ", " ███ ", "█████"],
    'S': [" ████████", "███      ", "███      ", " ███████ ", "      ███", "      ███", "████████ "],
}
# CGA attributes (fg | bg << 4); 0x0E yellow, 0x0C bright red, 0x04 red, 0x06 brown/orange
BAND = [(FULL, 0x0E), (TOP, 0x6E), (FULL, 0x06), (TOP, 0x46), (FULL, 0x0C), (FULL, 0x04), (FULL, 0x04)]


def draw():
    rnd = random.Random(2026)
    grid = [[(0x20, 0x07) for _ in range(W)] for _ in range(H)]

    def put(r, c, ch, attr):
        if 0 <= r < H and 0 <= c < W:
            grid[r][c] = (ch, attr)

    mask = [[False] * W for _ in range(H)]
    top, col = 0, 3
    for letter in "AXIS":
        rows = LETTERS[letter]
        for r, line in enumerate(rows):
            for c, px in enumerate(line):
                if px == '█':
                    mask[top + r][col + 2 * c] = mask[top + r][col + 2 * c + 1] = True
        col += 2 * len(rows[0]) + 4

    # spray specks behind everything
    for _ in range(70):
        r, c = rnd.randrange(H - 1), rnd.randrange(W)
        put(r, c, rnd.choice([LIGHT, DOT, DOT, 0xF9]), rnd.choice([0x05, 0x0D, 0x03, 0x08, 0x08]))
    # drop shadow: one right, one down
    for r in range(H):
        for c in range(W):
            if mask[r][c] and r + 1 < H and c + 1 < W and not mask[r + 1][c + 1]:
                put(r + 1, c + 1, LIGHT, 0x08)
    # letters: paint gradient band by row
    for r in range(H):
        for c in range(W):
            if mask[r][c]:
                ch, attr = BAND[r - top]
                put(r, c, ch, attr)
    # gloss: a white glint at the top-left of each stroke
    for r in range(top, top + 3):
        for c in range(1, W):
            if mask[r][c] and not mask[r][c - 1] and rnd.random() < 0.6:
                put(r, c, BOT if r == top else FULL, 0x0F if r == top else 0x0E)
    # drips off the bottom: red runs, some orange, a few drops falling away
    base = top + 6
    for c in range(W):
        if not mask[base][c] or rnd.random() > 0.6:
            continue
        length = rnd.choice([1, 1, 2, 2, 3, 3, 4])
        colour = rnd.choice([0x04, 0x04, 0x04, 0x06, 0x0C])
        rr = base + 1
        for i in range(length):
            put(rr, c, FULL if i < length - 1 else TOP, colour)
            rr += 1
        if rnd.random() < 0.4 and rr + 1 < H - 1:
            put(rr + 1, c, BOT, colour)
    # banner
    name = "U N D E R G R O U N D    C N C"
    c0 = (W - len(name) - 6) // 2
    banner = [(0xDE, 0x05), (0x20, 0x50), (0x20, 0x50)] + [(ord(ch), 0x5F if ch != ' ' else 0x50) for ch in name] + \
             [(0x20, 0x50), (0x20, 0x50), (0xDD, 0x05)]
    for i, (ch, attr) in enumerate(banner):
        put(H - 1, c0 + i, ch, attr)
    return grid


def to_ansi(grid):
    cga = [0, 4, 2, 6, 1, 5, 3, 7]  # CGA index -> ANSI colour number
    data = bytearray()
    for r, row in enumerate(grid):
        last = None
        for ch, attr in row:
            if attr != last:
                fg, bg = attr & 15, attr >> 4
                data += f"\x1b[0;{'1;' if fg > 7 else ''}{30 + cga[fg & 7]};{40 + cga[bg & 7]}m".encode()
                last = attr
            data.append(ch)
        # every row fills all 80 columns: BBS terminals wrap right after column 80, so a CR LF here
        # would leave a blank line under each row (SyncTERM showed the logo torn apart)
    data += b"\x1b[0m"
    return bytes(data)


def header(data, dst):
    out = ["// Generated by tools/art/make_login.py from art/login.ans. Do not edit; edit the .ans.",
           "// SPDX-License-Identifier: GPL-3.0-or-later", "// Copyright (C) 2026 Rev. J. Money",
           "#pragma once", "", "// The caller welcome logo: 80x12 CP437 ANSI, full-width rows with no CR LF (terminals wrap at column 80).",
           "static const char kLoginArt[] ="]
    line = ''
    for b in data:
        line += f'\\x{b:02x}'
        if len(line) > 100:
            out.append(f'    "{line}"')
            line = ''
    if line:
        out.append(f'    "{line}"')
    out[-1] += ';'
    open(dst, 'w', newline='\n').write('\n'.join(out) + '\n')


def main(args):
    if args[0] == '--header-only':
        header(open(args[1], 'rb').read(), args[2])
        return
    data = to_ansi(draw())
    open(args[0], 'wb').write(data)
    header(data, args[1])
    print(args[0], len(data), 'bytes')


if __name__ == '__main__':
    main(sys.argv[1:])
