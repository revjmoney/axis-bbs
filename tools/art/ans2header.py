"""Turn an 80x30 ANSI screen into a firmware header of CP437 cells, plus a PNG preview.

usage: python -I tools/art/ans2header.py art/wfc.ans src/platform/cyd/wfc_art.h kWfcArt [preview.png]
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', 'screenshots'))
import bbs_shots  # noqa: E402  (its little ANSI terminal)

bbs_shots.ROWS = 30
CGA_FROM_ANSI = [0, 4, 2, 6, 1, 5, 3, 7]


def main(src, dst, name, preview=None):
    term = bbs_shots.Term()
    term.feed(open(src, 'rb').read().decode('cp437'))
    out = ["// Generated by tools/art/ans2header.py from " + os.path.basename(src) + ". Do not edit; edit the .ans.",
           "#pragma once", "#include <stdint.h>",
           f"static const uint8_t {name}[30][80][2] = {{"]
    for row in term.cells:
        cells = []
        for g, fg, bg in row:
            ch = g.encode('cp437')[0]
            # Term keeps ANSI colour numbers; the firmware wants CGA attributes
            fgc = CGA_FROM_ANSI[fg & 7] | (fg & 8)
            bgc = CGA_FROM_ANSI[bg & 7]
            cells.append(f"{{{ch},{fgc | bgc << 4}}}")
        out.append("  {" + ",".join(cells) + "},")
    out.append("};")
    open(dst, 'w').write("\n".join(out) + "\n")
    print(dst)
    if preview:
        term.png(preview, os.path.basename(src))
        print(preview)


if __name__ == '__main__':
    main(*sys.argv[1:])
